"""Builds src/data/usPlaces.ts from GeoNames' cities5000 dump (CC BY 4.0).

    curl -O https://download.geonames.org/export/dump/cities5000.zip && unzip cities5000.zip
    python3 scripts/make-us-places.py cities5000.txt

Every US place with 5,000+ people, biggest first, as "Name|ST|lat|lon" rows.
"""
import os
import sys

rows = []
with open(sys.argv[1], encoding='utf-8') as f:
    for line in f:
        c = line.rstrip('\n').split('\t')
        if c[8] != 'US' or not c[10]:
            continue
        rows.append((int(c[14] or 0), c[1], c[10], float(c[4]), float(c[5])))
rows.sort(key=lambda r: -r[0])

body = '\n'.join(f'{name}|{st}|{lat:.3f}|{lon:.3f}' for _, name, st, lat, lon in rows)
out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src/data/usPlaces.ts')
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by scripts/make-us-places.py — do not edit by hand.\n')
    f.write('// US places with 5,000+ people, biggest first: "Name|ST|lat|lon".\n')
    f.write('// Source: GeoNames (geonames.org), licensed CC BY 4.0.\n')
    f.write('export default `' + body.replace('`', "'") + '`\n')
print(len(rows), 'places ->', out, os.path.getsize(out) // 1024, 'KB')
